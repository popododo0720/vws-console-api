// Command ec2gen generates EC2 query parity cases from the pinned model.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"slices"
	"strings"

	"github.com/popododo0720/vws-console-api/internal/awsmodel"
)

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(args []string) error {
	flags := flag.NewFlagSet("ec2gen", flag.ContinueOnError)
	served := flags.String("served", "", "file listing served operations")
	out := flags.String("out", "", "generated test file")
	if err := flags.Parse(args); err != nil {
		return fmt.Errorf("parse ec2gen flags: %w", err)
	}
	if *served == "" || *out == "" || flags.NArg() != 0 {
		return fmt.Errorf("ec2gen requires -served and -out and no positional arguments")
	}
	data, err := os.ReadFile(*served)
	if err != nil {
		return fmt.Errorf("read served actions: %w", err)
	}
	actions := strings.Fields(string(data))
	if len(actions) == 0 || !slices.IsSorted(actions) || len(slices.Compact(slices.Clone(actions))) != len(actions) {
		return fmt.Errorf("served actions must be nonempty, unique and sorted")
	}
	model, err := awsmodel.LoadEC2()
	if err != nil {
		return fmt.Errorf("load generator model: %w", err)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by ec2gen from botocore 1.44.1 ec2-2016-11-15. DO NOT EDIT.\n\n")
	b.WriteString("package ec2query\n\nfunc modelOperations() []string {\nreturn []string{\n")
	for _, name := range model.Operations() {
		fmt.Fprintf(&b, "%q,\n", name)
	}
	b.WriteString("}\n}\n\n")
	b.WriteString("type modelQueryKey struct { path string; required bool }\n")
	b.WriteString("type modelAction struct { name string; keys []modelQueryKey }\n\n")
	b.WriteString("func modelActions() []modelAction {\nreturn []modelAction{\n")
	for _, action := range actions {
		keys, err := model.QueryKeys(action)
		if err != nil {
			return fmt.Errorf("generate %s: %w", action, err)
		}
		fmt.Fprintf(&b, "{name: %q, keys: []modelQueryKey{\n", action)
		for _, key := range keys {
			fmt.Fprintf(&b, "{path: %q, required: %t},\n", key.Path, key.Required)
		}
		b.WriteString("}},\n")
	}
	b.WriteString("}\n}\n")
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("format generated cases: %w", err)
	}
	if err := os.WriteFile(*out, formatted, 0o600); err != nil {
		return fmt.Errorf("write generated cases: %w", err)
	}
	return nil
}
